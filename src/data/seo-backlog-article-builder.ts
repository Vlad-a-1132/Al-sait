function sentenceCase(value: string) {
  return value ? value[0].toUpperCase() + value.slice(1) : value;
}

function articleTitle(seed: BacklogArticleSeed) {
  const topic = sentenceCase(seed.topic);
  if (/как пережить развод/i.test(seed.topic)) return `${topic}: поддержка психолога и план восстановления | Альтамед-С`;
  if (/врач |обследование|массаж|брекет|коронк|мост |прикус|зубы мудрости|полное обследование/i.test(seed.topic)) {
    return `${topic}: консультация, диагностика и варианты решения | Альтамед-С`;
  }
  return `${topic}: причины, обследование и консультация врача | Альтамед-С`;
}

function articleDescription(seed: BacklogArticleSeed, profile: DirectionProfile) {
  return `${sentenceCase(seed.topic)}: что важно отметить, как проходит консультация и какие обследования может выбрать ${profile.specialist}. Запись в Альтамед-С в Одинцово.`;
}

